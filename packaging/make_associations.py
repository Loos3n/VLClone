"""Write build/associations.iss: the installer's file-type and Explorer entries.

Generated from vlclone/core/associations.py (the same data the app uses for
per-user registration), so the two never drift apart. Every entry belongs to
an opt-in installer task and is removed on uninstall:

* keys VLClone owns (ProgIDs, Capabilities, Explorer verbs): deleted whole;
* values in shared keys (.mkv\\OpenWithProgids, RegisteredApplications): only ours;
* an extension's default: set only when no program had one, and on uninstall
  removed only if it still points at VLClone (see [Code] in installer.iss).
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from vlclone.core.associations import (ASSOCIATION_TYPES, association_entries,  # noqa: E402
                                       context_menu_entries, default_candidates)

EXE = "{app}\\VLClone.exe"
TASKS = {"video": "assoc\\video", "audio": "assoc\\audio", "playlist": "assoc\\playlist",
         "context": "contextmenu"}


def iss_str(text: str) -> str:
    # Inno: double quotes are doubled, braces that are not constants are doubled.
    text = text.replace("{", "{{").replace("{{app}", "{app}")
    return '"' + text.replace('"', '""') + '"'


def registry_lines() -> list[str]:
    lines: list[str] = []
    seen: set[tuple[str, str, str]] = set()
    entries = [(e, TASKS.get(e.category, " or ".join(TASKS[c] for c in ASSOCIATION_TYPES)))
               for e in association_entries(list(ASSOCIATION_TYPES), EXE)]
    entries += [(e, TASKS["context"]) for e in context_menu_entries(EXE)]
    for e, tasks in entries:
        key = (e.key.lower(), e.name.lower(), tasks)
        if key in seen:
            continue
        seen.add(key)
        if e.owned_key and e.key.lower() == e.owned_key.lower():
            flags = "uninsdeletekey"
        elif e.owned_key:
            flags = "uninsdeletekey"  # inside an owned key: the owned key goes on uninstall
        else:
            flags = "uninsdeletevalue"
        name = f"ValueName: {iss_str(e.name)}; " if e.name else ""
        lines.append(f"Root: HKA; Subkey: {iss_str(e.key)}; ValueType: string; {name}"
                     f"ValueData: {iss_str(e.value)}; Flags: {flags}; Tasks: {tasks}")
    any_assoc = " or ".join(TASKS[c] for c in ASSOCIATION_TYPES)
    lines.append(f'Root: HKA; Subkey: "Software\\VLClone"; Flags: uninsdeletekeyifempty; Tasks: {any_assoc}')
    # Defaults only where no program has one yet (Windows keeps the user's own choice anyway).
    for key, progid in default_candidates(list(ASSOCIATION_TYPES)):
        cat = next(c for c, (p, _, _) in ASSOCIATION_TYPES.items() if p == progid)
        ext = key.rsplit("\\", 1)[1]
        lines.append(f"Root: HKA; Subkey: {iss_str(key)}; ValueType: string; ValueData: {iss_str(progid)}; "
                     f"Tasks: {TASKS[cat]}; Check: NoDefaultFor('{ext}')")
    return lines


def code_lines() -> list[str]:
    calls = [f"  RemoveDefaultIfOurs('{key.rsplit(chr(92), 1)[1]}', '{progid}');"
             for key, progid in default_candidates(list(ASSOCIATION_TYPES))]
    return ["procedure RemoveOurDefaults();", "begin", *calls, "end;"]


def main(out: str = "build/associations.iss") -> None:
    path = ROOT / out if not Path(out).is_absolute() else Path(out)
    path.parent.mkdir(parents=True, exist_ok=True)
    text = ["; Generated by packaging/make_associations.py from vlclone/core/associations.py. Do not edit.",
            "[Registry]", *registry_lines(), "", "[Code]", *code_lines(), ""]
    path.write_text("\n".join(text), encoding="utf-8")
    print(f"wrote {path} ({len(text)} lines)")


if __name__ == "__main__":
    main(*sys.argv[1:])
